-- ------------------------------------------------------------------- views
-- security_invoker: the views run with the caller's RLS, they don't bypass it.
create view public.catalog_products with (security_invoker = true) as
select
  p.id, p.name, p.title, p.price, p.discount_percent, p.original_price, p.image,
  p.category_id, c.name as category, p.stock_count, p.specs,
  p.is_best_seller, p.is_trending, p.is_active, p.created_at, p.updated_at,
  case when p.base_review_count + coalesce(r.n, 0) = 0 then 0
       else round((p.base_rating * p.base_review_count + coalesce(r.total, 0))
                  / (p.base_review_count + coalesce(r.n, 0)), 1)
  end as rating,
  p.base_review_count + coalesce(r.n, 0) as review_count
from public.products p
join public.categories c on c.id = p.category_id
left join (
  select product_id, count(*) as n, sum(rating) as total
  from public.product_reviews where status = 'Approved' group by product_id
) r on r.product_id = p.id;

-- Customer list for the admin panel: profile + real order aggregates.
create view public.admin_customers with (security_invoker = true) as
select
  pr.id, pr.name, pr.email, pr.phone, pr.status, pr.role, pr.created_at as joined,
  coalesce(o.orders, 0)       as orders,
  coalesce(o.total_spent, 0)  as total_spent,
  o.last_order_at,
  (select ship_city from public.orders x where x.user_id = pr.id order by x.created_at desc limit 1) as city
from public.profiles pr
left join (
  select user_id, count(*) as orders,
         sum(total) filter (where status not in ('Cancelled', 'Returned')) as total_spent,
         max(created_at) as last_order_at
  from public.orders where user_id is not null group by user_id
) o on o.user_id = pr.id;
