-- SmartCart: core schema (Phase 1)
-- Derived from the existing frontend data model (products, categories, cart,
-- wishlist, addresses, coupons, orders, reviews, returns, promo banner).

-- ---------------------------------------------------------------- helpers
create or replace function public.set_updated_at()
returns trigger language plpgsql as $$
begin
  new.updated_at = now();
  return new;
end $$;

-- ---------------------------------------------------------------- profiles
-- One row per auth.users row. Created by trigger (see security migration).
create table public.profiles (
  id          uuid primary key references auth.users(id) on delete cascade,
  name        text not null default '',
  email       text not null default '',
  phone       text,
  role        text not null default 'customer' check (role in ('customer', 'admin')),
  status      text not null default 'Active'   check (status in ('Active', 'Blocked')),
  created_at  timestamptz not null default now(),
  updated_at  timestamptz not null default now()
);
create index profiles_role_idx on public.profiles (role);
create trigger profiles_updated_at before update on public.profiles
  for each row execute function public.set_updated_at();

-- -------------------------------------------------------------- categories
-- The frontend identifies a category by its name string (e.g. 'under 40 rupee').
create table public.categories (
  id           bigint generated always as identity primary key,
  name         text not null,
  icon         text not null default '🍽️',
  description  text not null default '',
  status       text not null default 'Active' check (status in ('Active', 'Inactive')),
  sort_order   integer not null default 0,
  created_at   timestamptz not null default now(),
  updated_at   timestamptz not null default now()
);
create unique index categories_name_uq on public.categories (lower(name));
create trigger categories_updated_at before update on public.categories
  for each row execute function public.set_updated_at();

-- ---------------------------------------------------------------- products
-- ids are kept from list.json (1..N) because /product/:id, carts and wishlists
-- reference them. `generated by default` lets the seed insert explicit ids.
create table public.products (
  id                 bigint generated by default as identity primary key,
  name               text not null check (length(btrim(name)) > 0),
  title              text not null default '',           -- short description (list.json "title")
  price              numeric(10,2) not null check (price >= 0),
  discount_percent   integer not null default 0 check (discount_percent between 0 and 90),
  -- same formula as the old buildProduct(): originalPrice = round(price / (1 - d/100))
  original_price     numeric(10,2) generated always as (
                       case when discount_percent > 0
                            then round(price / (1 - discount_percent / 100.0))
                            else price end
                     ) stored,
  image              text not null default '',
  category_id        bigint not null references public.categories(id) on delete restrict,
  stock_count        integer not null default 0 check (stock_count >= 0),
  -- Catalog baseline rating (frozen from the old generated values). Real approved
  -- reviews are blended on top of it in the catalog_products view.
  base_rating        numeric(2,1) not null default 0 check (base_rating between 0 and 5),
  base_review_count  integer not null default 0 check (base_review_count >= 0),
  specs              jsonb not null default '{}'::jsonb,
  is_best_seller     boolean not null default false,
  is_trending        boolean not null default false,
  is_active          boolean not null default true,
  created_at         timestamptz not null default now(),
  updated_at         timestamptz not null default now()
);
create index products_category_idx on public.products (category_id);
create index products_active_idx   on public.products (is_active);
create trigger products_updated_at before update on public.products
  for each row execute function public.set_updated_at();

-- ---------------------------------------------------------- product_reviews
create table public.product_reviews (
  id          bigint generated always as identity primary key,
  product_id  bigint not null references public.products(id) on delete cascade,
  user_id     uuid references public.profiles(id) on delete set null,
  author      text not null default 'Verified Buyer',
  rating      smallint not null check (rating between 1 and 5),
  text        text not null check (length(btrim(text)) > 0),
  status      text not null default 'Pending' check (status in ('Pending', 'Approved', 'Hidden')),
  created_at  timestamptz not null default now(),
  updated_at  timestamptz not null default now()
);
create index product_reviews_product_idx on public.product_reviews (product_id, status);
create unique index product_reviews_one_per_user on public.product_reviews (product_id, user_id) where user_id is not null;
create trigger product_reviews_updated_at before update on public.product_reviews
  for each row execute function public.set_updated_at();

