-- ------------------------------------------------------------------ orders
create sequence public.order_number_seq start 10000001;
create sequence public.return_number_seq start 3001;

create table public.orders (
  id               bigint generated always as identity primary key,
  -- same "SC" + 8 digits format as the old client-generated ids
  order_number     text not null unique default ('SC' || nextval('public.order_number_seq')),
  user_id          uuid references public.profiles(id) on delete set null,
  status           text not null default 'Pending' check (status in (
                     'Pending','Confirmed','Processing','Packed','Shipped',
                     'Out for Delivery','Delivered','Cancelled','Returned')),
  subtotal         numeric(10,2) not null check (subtotal >= 0),
  delivery_fee     numeric(10,2) not null default 0 check (delivery_fee >= 0),
  savings          numeric(10,2) not null default 0 check (savings >= 0),
  coupon_code      text,
  coupon_discount  numeric(10,2) not null default 0 check (coupon_discount >= 0),
  total            numeric(10,2) not null check (total >= 0),
  ship_name        text not null,
  ship_email       text not null,
  ship_phone       text not null check (ship_phone ~ '^[0-9]{10}$'),
  ship_line1       text not null,
  ship_city        text not null,
  ship_pincode     text not null check (ship_pincode ~ '^[0-9]{6}$'),
  stock_restored   boolean not null default false,
  created_at       timestamptz not null default now(),
  updated_at       timestamptz not null default now()
);
create index orders_user_idx    on public.orders (user_id, created_at desc);
create index orders_status_idx  on public.orders (status);
create index orders_created_idx on public.orders (created_at desc);
create trigger orders_updated_at before update on public.orders
  for each row execute function public.set_updated_at();

